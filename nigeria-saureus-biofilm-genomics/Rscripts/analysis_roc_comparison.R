library(pROC)
df <- read.csv("biofilm_analysis_dataset_expanded.csv")
df$mrsa_binary <- ifelse(df$MRSA_Status == "MRSA", 1, 0)
m1 <- glm(mrsa_binary ~ biofilm_score, data = df, family = binomial)
m2 <- glm(mrsa_binary ~ sdrD, data = df, family = binomial)
m3 <- glm(mrsa_binary ~ MLST, data = df, family = binomial)
p1 <- predict(m1, type = "response")
p2 <- predict(m2, type = "response")
p3 <- predict(m3, type = "response")
r1 <- roc(df$mrsa_binary, p1)
r2 <- roc(df$mrsa_binary, p2)
r3 <- roc(df$mrsa_binary, p3)
comp12 <- roc.test(r1, r2, method = "delong")
comp13 <- roc.test(r1, r3, method = "delong")
comp23 <- roc.test(r2, r3, method = "delong")
cat("AUC full:", auc(r1), "\nAUC sdrD:", auc(r2), "\nAUC MLST:", auc(r3), "\n")
cat("Full vs sdrD p =", comp12$p.value, "\nFull vs MLST p =", comp13$p.value, "\n")
pdf("roc_comparison.pdf")
plot(r1, col = "blue", main = "")
lines(r2, col = "red")
lines(r3, col = "green")
legend("bottomright", legend = c("Full score", "sdrD", "MLST"), 
       col = c("blue", "red", "green"), lwd = 2)
dev.off()
results <- data.frame(Model = c("Full", "sdrD", "MLST"),
                      AUC = c(auc(r1), auc(r2), auc(r3)))
write.csv(results, "roc_comparison_results.csv", row.names = FALSE)
